import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are RoadBuddy Bot, an intelligent multilingual roadside assistance chatbot. You help stranded travelers get emergency help.

Your capabilities:
- Understand roadside emergency intents: tyre puncture, vehicle breakdown, battery dead, fuel empty, towing request, mechanic search
- Respond in the user's language. You support English, Tamil (தமிழ்), Hindi (हिन्दी), Kannada (ಕನ್ನಡ), and Telugu (తెలుగు).
- If the user writes in a specific language, respond in that same language.
- Ask contextual follow-up questions like location, vehicle type, and urgency level.
- Be professional, calm, and reassuring — this is emergency assistance.
- Keep responses concise (2-3 sentences max).
- When appropriate, suggest actions: requesting help, finding nearby mechanics, calling support, or joining as a partner.
- If the user greets you, introduce yourself and ask how you can help.
- Never make up phone numbers or addresses.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages, language } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemMessages = [
      { role: "system", content: SYSTEM_PROMPT },
    ];

    if (language && language !== "en") {
      systemMessages.push({
        role: "system",
        content: `The user has selected ${language} as their preferred language. Always respond in ${language}.`,
      });
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [...systemMessages, ...messages],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again shortly." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add credits." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(
      JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
